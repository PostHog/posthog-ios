#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(git rev-parse --show-toplevel)"
UPDATE=false
NO_TRAITS=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        -u|--update)
            UPDATE=true
            shift
            ;;
        --no-traits)
            NO_TRAITS=true
            shift
            ;;
        -\?|-h|--help)
            cat <<'EOF'
Usage: scripts/check-public-api.sh [--update] [--no-traits]

Checks the PostHog Swift public API snapshot.
Use --update after intentional public API changes.
Use --no-traits to check the Swift Package Manager build with every package trait
disabled against api/posthog-ios.public-api.no-traits.txt.
EOF
            exit
            ;;
        *)
            echo "Unknown option: $1" >&2
            exit 1
            ;;
    esac
done

if $NO_TRAITS; then
    SNAPSHOT_FILE="$ROOT_DIR/api/posthog-ios.public-api.no-traits.txt"
    UPDATE_COMMAND="scripts/check-public-api.sh --update --no-traits"
    SCOPE="public/open symbols emitted for the PostHog iOS symbol graphs, Swift Package Manager build with --disable-default-traits."
else
    SNAPSHOT_FILE="$ROOT_DIR/api/posthog-ios.public-api.txt"
    UPDATE_COMMAND="scripts/check-public-api.sh --update"
    SCOPE="public/open symbols emitted for the PostHog iOS symbol graphs."
fi

TMP_FILE="$(mktemp)"
BUILD_DIR="$(mktemp -d)"
SYMBOLGRAPH_DIR="$(mktemp -d)"
cleanup() {
    rm -f "$TMP_FILE"
    rm -rf "$BUILD_DIR" "$SYMBOLGRAPH_DIR"
}
trap cleanup EXIT

cd "$ROOT_DIR"
set -o pipefail
IOS_SDK="$(xcrun --sdk iphoneos --show-sdk-path)"
EXTRA_EXTRACT_ARGS=()

if $NO_TRAITS; then
    xcrun swift build \
        --target PostHog \
        --disable-default-traits \
        --triple arm64-apple-ios15.0 \
        --sdk "$IOS_SDK" \
        --build-path "$BUILD_DIR" \
        >/dev/null

    PRODUCTS_DIR="$BUILD_DIR/arm64-apple-ios/debug"
    MODULES_DIR="$PRODUCTS_DIR/Modules"
    if [[ ! -d "$MODULES_DIR" ]]; then
        MODULES_DIR="$PRODUCTS_DIR"
    fi
    EXTRA_EXTRACT_ARGS=(
        -I "$MODULES_DIR"
        -Xcc -fmodule-map-file="$PRODUCTS_DIR/PostHogObjCExceptionSupport.build/module.modulemap"
    )
else
    xcrun xcodebuild build \
        -scheme PostHog \
        -destination generic/platform=ios \
        -derivedDataPath "$BUILD_DIR" \
        | xcpretty >/dev/null

    PRODUCTS_DIR="$(find "$BUILD_DIR/Build/Products" -maxdepth 1 -type d -name '*iphoneos' | head -n 1)"
    EXTRA_EXTRACT_ARGS=(-F "$PRODUCTS_DIR")
fi

if [[ -z "$PRODUCTS_DIR" || ! -d "$PRODUCTS_DIR" ]]; then
    echo "No iOS build products found under $BUILD_DIR" >&2
    exit 1
fi

xcrun swift-symbolgraph-extract \
    -module-name PostHog \
    -target arm64-apple-ios15.0 \
    -sdk "$IOS_SDK" \
    -I "$PRODUCTS_DIR" \
    "${EXTRA_EXTRACT_ARGS[@]}" \
    -minimum-access-level public \
    -skip-synthesized-members \
    -output-dir "$SYMBOLGRAPH_DIR"

python3 - "$SYMBOLGRAPH_DIR" "$TMP_FILE" "$UPDATE_COMMAND" "$SCOPE" <<'PY'
import json
import sys
from pathlib import Path

symbolgraph_dir = Path(sys.argv[1])
out = Path(sys.argv[2])
update_command = sys.argv[3]
scope = sys.argv[4]
if not symbolgraph_dir.exists():
    raise SystemExit(f'No Swift symbol graph output found under {symbolgraph_dir}')

records = []
for path in sorted(symbolgraph_dir.glob('PostHog*.symbols.json')):
    data = json.loads(path.read_text())
    module = data.get('module', {}).get('name', path.stem.removesuffix('.symbols'))
    for symbol in data.get('symbols', []):
        access = symbol.get('accessLevel', '')
        if access not in {'public', 'open'}:
            continue
        kind = symbol.get('kind', {}).get('identifier', 'unknown').replace('swift.', '')
        precise = symbol.get('identifier', {}).get('precise', '')
        path_components = '.'.join(symbol.get('pathComponents', []))
        if path_components == 'char8_t' and precise.startswith('c:PostHog-Swift.h@T@'):
            continue
        declaration = ''.join(fragment.get('spelling', '') for fragment in symbol.get('declarationFragments', []))
        records.append((module, path_components, kind, declaration, precise))

if not records:
    raise SystemExit('No public PostHog symbols found in generated symbol graphs')

lines = [
    f'# This file is generated by `{update_command}`.',
    '# Do not edit manually.',
    f'# Public API scope: {scope}',
    '',
]
for module, path_components, kind, declaration, precise in sorted(set(records)):
    lines.append(f'{module} | {path_components} | {kind} | {declaration} | {precise}')

out.write_text('\n'.join(lines) + '\n')
PY

if $UPDATE; then
    mkdir -p "$(dirname "$SNAPSHOT_FILE")"
    cp "$TMP_FILE" "$SNAPSHOT_FILE"
    echo "Updated $SNAPSHOT_FILE"
    exit
fi

if [[ ! -f "$SNAPSHOT_FILE" ]]; then
    echo "Missing public API snapshot: $SNAPSHOT_FILE" >&2
    echo "Run $UPDATE_COMMAND to create it." >&2
    exit 1
fi

if diff -u "$SNAPSHOT_FILE" "$TMP_FILE"; then
    echo "Swift public API snapshot $(basename "$SNAPSHOT_FILE") is up to date."
else
    echo "Swift public API changed. Run $UPDATE_COMMAND if intentional." >&2
    exit 1
fi
